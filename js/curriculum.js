window.KP_INDEX = (function () {
  var idx = {};
  window.CURRICULUM.forEach(function (sem) {
    sem.units.forEach(function (u) {
      u.kps.forEach(function (kp) {
        idx[kp.name] = {
          name: kp.name,
          semester: sem.semester,
          short: sem.short,
          unit: u.unit,
          aliases: kp.aliases
        };
      });
    });
  });
  return idx;
})();
